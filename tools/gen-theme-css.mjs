// Makes app/src/ui/themes.css from the shared package's design_preview themes.css (vendor/hometv-launcher, the commit
// the submodule pins). The design's file works out soft fills with color-mix() and uses :is(), which the TV's
// Chromium (53 on webOS 4) does not have, so here every colour mix is worked out ahead and written as a plain rgba.
// Usage: node tools/gen-theme-css.mjs   (writes app/src/ui/themes.css; tests/themes.test.mjs checks it is up to date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = path.join(root, 'vendor/hometv-launcher/design_preview/src/styles/themes.css');
export const OUT = path.join(root, 'app/src/ui/themes.css');

/** "#rrggbb" or "rgba(r, g, b, a)" as [r, g, b, a]. */
export function parseColor(s) {
  s = s.trim();
  let m = /^#([0-9a-f]{6})$/i.exec(s);
  if (m) return [0, 2, 4].map((i) => parseInt(m[1].substr(i, 2), 16)).concat(1);
  m = /^rgba?\(([^)]*)\)$/.exec(s);
  if (!m) throw new Error('colour not understood: ' + s);
  const p = m[1].split(',').map(Number);
  return [p[0], p[1], p[2], p.length > 3 ? p[3] : 1];
}

const num = (n) => String(Math.round(n * 1000) / 1000);
export const rgba = (c) => `rgba(${Math.round(c[0])}, ${Math.round(c[1])}, ${Math.round(c[2])}, ${num(c[3])})`;

/** color-mix(in srgb, c p%, transparent): the colour with its alpha scaled. */
export const withAlpha = (c, p) => [c[0], c[1], c[2], c[3] * p];

/** color-mix(in srgb, a p%, b): premultiplied interpolation, as CSS does it. */
export function mix(a, b, p) {
  const alpha = a[3] * p + b[3] * (1 - p);
  const ch = (i) => (a[i] * a[3] * p + b[i] * b[3] * (1 - p)) / (alpha || 1);
  return [ch(0), ch(1), ch(2), alpha];
}

export function build(src) {
  const text = src.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(text))) {
    const sel = m[1].trim();
    if (sel === "[data-theme]:not([data-theme='midnight'])") continue; // the color-mix block: written below, per theme
    if (/:is\(/.test(sel)) continue; // rewritten below
    const decls = m[2]
      .split(';')
      .map((d) => d.trim())
      .filter(Boolean);
    const vars = {};
    for (const d of decls) {
      const i = d.indexOf(':');
      vars[d.slice(0, i).trim()] = d.slice(i + 1).trim();
    }
    if (vars['--accent'] && vars['--surface']) {
      const surface = parseColor(vars['--surface']);
      decls.push(
        `--accent-soft: ${rgba(withAlpha(parseColor(vars['--accent']), 0.14))}`,
        `--good-soft: ${rgba(withAlpha(parseColor(vars['--good']), 0.16))}`,
        `--tile: ${rgba(withAlpha(surface, 0.9))}`,
        `--well: ${rgba(withAlpha(surface, 0.6))}`,
        `--pane: ${rgba(withAlpha(surface, 0.8))}`,
        `--pane-live: ${rgba(mix(surface, parseColor(vars['--surface-2']), 0.875))}`,
      );
    }
    out.push(`${sel} {\n${decls.map((d) => `  ${d};`).join('\n')}\n}`);
  }
  out.push(`/* A downloaded backdrop sits on the theme's sky, which is all there is while it loads or when it can't be fetched. */
html[data-backdrop='url'],
html[data-backdrop='pixel'],
html[data-backdrop='plain'] {
  --sky: linear-gradient(var(--sky-top), var(--sky-mid) 55%, var(--horizon));
}

/* 8-bit's 160 × 90 pictures are scaled up without smoothing; what sits on them is drawn as usual. */
html[data-backdrop='pixel'] #stage {
  image-rendering: pixelated;
}
html[data-backdrop='pixel'] #stage > * {
  image-rendering: auto;
}`);
  return (
    `/* GENERATED by tools/gen-theme-css.mjs from the shared package's design_preview/src/styles/themes.css: edit that or\n` +
    `   the tool, then run it. The colour mixes the design does with color-mix() and :is() are written out as plain\n` +
    `   values, for Chromium 53. Midnight is the shared tokens.css. */\n\n` +
    out.join('\n\n') +
    '\n'
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUT, build(fs.readFileSync(SOURCE, 'utf8')));
  console.log('wrote ' + path.relative(root, OUT));
}
